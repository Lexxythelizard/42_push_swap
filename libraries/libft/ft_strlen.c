// --- includes ---

#include "libft.h"

// --- prototypes ---

size_t	ft_strlen(const char *s);

// --- define ---

size_t	ft_strlen(const char *s)
{
	size_t	len;

	len = 0;
	while (s[len])
		len++;
	return (len);
}
